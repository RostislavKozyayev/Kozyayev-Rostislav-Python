# B исходном текстовом файле (hotline1.txt) найти все номера телефонов, соответствующих шаблону 8(000)000-00-00.
# Посчитать количество полученных элементов. После фразы «Горячая линия» добавить фразу
# «Министерства образования Ростовской области», выполнив манипуляции в новом файле.

import re

# Открываем исходный файл
with open('hotline1.txt', 'rt', encoding='utf-8') as file:
    text = file.read()

# Шаблон для поиска номеров в формате 8(000)000-00-00
pattern = r'8\(\d{3}\)\d{3}-\d{2}-\d{2}'

# Находим все соответствующие номера
matching_numbers = re.findall(pattern, text)
print(f"Количество номеров в формате 8(000)000-00-00: {len(matching_numbers)}")

# Добавляем фразу после каждой "Горячая линия"
modified_text = re.sub(r'(«Горячая линия»)', r'\1 Министерства образования Ростовской области', text)

# Сохраняем в новый файл
with open('hotline_modified.txt', 'wt', encoding='utf-8') as file:
    file.write(modified_text)